    inline void Xor512(uint8_t* a, const uint8_t* b) {
        for (int i = 0; i < 64; i++) a[i] ^= b[i];
    }

    inline void AddMod512(uint8_t* a, const uint8_t* b) {
        uint16_t carry = 0;
        for (int i = 63; i >= 0; i--) {
            uint16_t sum = a[i] + b[i] + carry;
            a[i] = sum & 0xff;
            carry = sum >> 8;
        }
    }

    inline void AddMod512_32(uint8_t* a, uint32_t b) {
        uint64_t carry = b;
        for (int i = 63; i >= 0 && carry; i--) {
            uint64_t sum = a[i] + (carry & 0xff);
            a[i] = sum & 0xff;
            carry = (carry >> 8) + (sum >> 8);
        }
    }

    inline void S(uint8_t* out, const uint8_t* in) {
        for (int i = 0; i < 64; i++) out[i] = Pi[in[i]];
    }

    inline void P(uint8_t* out, const uint8_t* in) {
        for (int i = 0; i < 64; i++) out[i] = in[Tau[i]];
    }

    inline void L(uint8_t* out, const uint8_t* in) {
        for (int i = 0; i < 8; i++) {
            uint64_t v = 0;
            for (int j = 0; j < 8; j++) {
                v = (v << 8) | in[i * 8 + j];
            }
            uint64_t res = 0;
            for (int j = 0; j < 64; j++) {
                if ((v >> (63 - j)) & 1) res ^= A[j];
            }
            for (int j = 0; j < 8; j++) {
                out[i * 8 + j] = (res >> (56 - j * 8)) & 0xff;
            }
        }
    }

    inline void LPS(uint8_t* out, const uint8_t* in) {
        uint8_t tmp[64];
        S(tmp, in);
        P(tmp, tmp);
        L(out, tmp);
    }

    inline void E(uint8_t* out, const uint8_t* K, const uint8_t* m) {
        uint8_t state[64];
        memcpy(state, m, 64);
        Xor512(state, K);

        for (int i = 0; i < 12; i++) {
            uint8_t key[64];
            LPS(key, state);
            Xor512(key, C[i]);

            uint8_t tmp[64];
            memcpy(tmp, state, 64);
            Xor512(tmp, key);
            LPS(tmp, tmp);
            memcpy(state, tmp, 64);

            memcpy(key, state, 64);
        }

        memcpy(out, state, 64);
    }

