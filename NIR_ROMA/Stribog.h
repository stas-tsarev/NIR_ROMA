    inline void g(uint8_t* h, const uint8_t* N, const uint8_t* m) {
        uint8_t K[64];
        memcpy(K, h, 64);
        Xor512(K, N);
        LPS(K, K);

        uint8_t tmp[64];
        E(tmp, K, m);
        Xor512(tmp, h);
        Xor512(tmp, m);
        memcpy(h, tmp, 64);
    }

    inline void hash(const uint8_t* data, size_t len, uint8_t* out, size_t out_size) {
        uint8_t h[64];
        uint8_t N[64] = { 0 };
        uint8_t Sigma[64] = { 0 };

        if (out_size == 32) {
            memset(h, 0x01, 64);
        }
        else {
            memset(h, 0x00, 64);
        }

        size_t i = 0;
        while (i + 64 <= len) {
            uint8_t block[64];
            for (int j = 0; j < 64; j++) {
                block[j] = data[i + j];
            }

            g(h, N, block);
            AddMod512(N, (uint8_t*)"\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00"
                "\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00"
                "\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00"
                "\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x00\x02\x00");
            AddMod512(Sigma, block);

            i += 64;
        }

        size_t remaining = len - i;
        if (remaining > 0 || len == 0) {
            uint8_t block[64] = { 0 };
            for (size_t j = 0; j < remaining; j++) {
                block[j] = data[i + j];
            }
            block[remaining] = 0x01;

            g(h, N, block);

            uint8_t size_block[64] = { 0 };
            uint64_t bit_len = len * 8;
            for (int j = 0; j < 8; j++) {
                size_block[63 - j] = (bit_len >> (j * 8)) & 0xff;
            }
            AddMod512(N, size_block);
            AddMod512(Sigma, block);
        }

        g(h, N, Sigma);

        if (out_size == 32) {
            for (int j = 0; j < 32; j++) {
                out[j] = h[j];
            }
        }
        else {
            memcpy(out, h, 64);
        }
    }

    inline std::string toHex(const uint8_t* data, size_t len) {
        std::stringstream ss;
        for (size_t i = 0; i < len; i++) {
            ss << std::hex << std::setw(2) << std::setfill('0') << (int)data[i];
        }
        return ss.str();
    }

    // ==================== Публичный API ====================

    class Streebog {
    public:
        static std::string hashString(const std::string& message, size_t bits = 256) {
            size_t out_size = bits / 8;
            uint8_t out[64];
            hash(reinterpret_cast<const uint8_t*>(message.c_str()), message.size(), out, out_size);
            return toHex(out, out_size);
        }

        static std::string hashFile(const std::string& filename, size_t bits = 256) {
            std::ifstream file(filename, std::ios::binary);
            if (!file) {
                throw std::runtime_error("Cannot open file: " + filename);
            }

            std::vector<uint8_t> data((std::istreambuf_iterator<char>(file)),
                std::istreambuf_iterator<char>());
            return hashString(std::string(data.begin(), data.end()), bits);
        }
    };

